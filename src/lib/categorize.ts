/** Формальные формулировки без содержания. */
const FORMAL = [
  /по\s+собственному\s+желанию/gi,
  /по\s+соглашению\s+сторон/gi,
  /ст\.?\s*80\s*тк(\s*рф)?/gi,
  /п\.?\s*3\s*ч\.?\s*1\s*ст\.?\s*77/gi,
  /заявлени[ея]\s+работника/gi,
  /личное\s+заявление/gi,
  /по\s+инициативе\s+работника/gi,
  /расторжени[еяю]/gi,
  /трудов(ого|ой|ым)\s+договор(а|ом)?/gi,
  /увольнение/gi,
];

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, "е");
}

/** Только словарь: категория или null. */
export function matchDictionary(text: string): Category | null {
  const t = " " + normalize(text).replace(/[^a-zа-я0-9/ ]+/g, " ") + " ";
  let best: Category | null = null;
  let bestHits = 0;
  for (const [cat, stems] of Object.entries(DICTIONARY) as [Category, string[]][]) {
    let hits = 0;
    for (const stem of stems) {
      const s = normalize(stem);
      // начало слова: перед основой пробел
      if (t.includes(" " + s)) hits++;
    }
    if (hits > bestHits) {
      best = cat;
      bestHits = hits;
    }
  }
  return best;
}

/** Формальная причина или пустой текст. */
export function isFormal(text: string): boolean {
  let rest = text;
  for (const re of FORMAL) rest = rest.replace(re, " ");
  // Остались только предлоги и знаки («по», «в», «с»)? Тогда содержания нет.
  const words = rest.toLowerCase().split(/[^a-zа-яё0-9]+/).filter((w) => w.length > 2);
  return words.length === 0;
}

/** Синхронный разбор: формальная -> словарь -> «Другое». */
export function categorizeText(text: string): Categorized {
  if (isFormal(text)) return { category: NOT_SPECIFIED, source: "none" };
  const cat = matchDictionary(text);
  if (cat) return { category: cat, source: "dictionary" };
  return { category: "Другое", source: "none" };
}

/** Нужно ли просить LLM уточнить категорию. */
export function needsLlm(text: string, c: Categorized | null): boolean {
  return !!c && c.category === "Другое" && c.source === "none" && text.trim().length > 0;
}

